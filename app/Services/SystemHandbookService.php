    /**
     * التحقق الأمني من صلاحية وصول المستخدم لهذا المقال بالذات
     */
    public static function canUserAccessGuide(array $guide, ?User $user): bool
    {
        $audiences = $guide['target_audience'] ?? [$guide['role'] ?? 'admin'];

        // 1. إذا كان زائراً غير مسجل: يسمح فقط بمقالات الزوار العامة (guest)
        if (!$user) {
            return in_array('guest', $audiences, true);
        }

        // 2. كادر الإدارة، المشرفون، المعلمون، والمحاسبون:
        // تنفيذاً لطلب المستخدم: يملكون حق قراءة الدليل كاملاً وسؤال المساعد الذكي عن أي عملية
        if ($user->isAdmin() || $user->isSupervisor() || $user->isTeacher() || $user->isAccountant() || ($user->permissionGroup && $user->permissionGroup->isAdminGroup())) {
            return true;
        }

        // 3. الطالب المسجل: يرى فقط أدلة الطلاب والزوار العامة
        if ($user->isStudent()) {
            return in_array('student', $audiences, true) || in_array('guest', $audiences, true);
        }

        // 4. ولي الأمر: يرى فقط أدلة أولياء الأمور والزوار العامة
        if ($user->isParent()) {
            return in_array('parent', $audiences, true) || in_array('guest', $audiences, true);
        }

        return false;
    }

    /**
     * جلب الأدلة المخصصة والمسموحة للمستخدم الحالي بحسب رتبته وصلاحياته
     */
    public static function getGuidesForUser(?User $user): array
    {
        $all = self::getAllGuides();
        return array_values(array_filter($all, function ($g) use ($user) {
            return self::canUserAccessGuide($g, $user);
        }));
    }

    /**
     * توسيع مرادفات الأفعال والمصادر العربية لتحسين دقة استخراج النية
     */
    public static function expandArabicSynonyms(string $text): string
    {
        $replacements = [
            '/\b(اضيف|اضف|نضيف)\b/u' => 'اضافة',
            '/\b(انشئ|اصنع|اعمل|اسوي|نسوي|ننشئ)\b/u' => 'انشاء',
            '/\b(اسجل|تسجل|نسجل)\b/u' => 'تسجيل',
            '/\b(اربط|نربط)\b/u' => 'ربط',
            '/\b(ارصد|نرصد)\b/u' => 'رصد',
            '/\b(اصدر|نصدر|اطبع)\b/u' => 'اصدار',
            '/\b(اؤدي|اودي|اختبر|احل|نحل)\b/u' => 'اداء',
            '/\b(احضر|ادخل|ندخل)\b/u' => 'حضور',
            '/\b(اعدل|نعدل)\b/u' => 'تعديل',
            '/\b(احذف|نحذف)\b/u' => 'حذف',
            '/\b(اسند|نسند)\b/u' => 'اسناد',
        ];
        return preg_replace(array_keys($replacements), array_values($replacements), $text);
    }

    /**
     * البحث الذكي في مقالات المساعدة بناءً على السؤال وهوية المستخدم
     */
    public static function searchHelp(string $query, ?User $user = null): ?array
    {
        $normalized = SmartBotService::normalizeText($query);
        $expanded = SmartBotService::normalizeText(self::expandArabicSynonyms($normalized));
        $guides = self::getAllGuides();

        // فحص طلب دليل النظام العام
        $generalHelpKeywords = ['مساعدة', 'دليل النظام', 'دليل الاستخدام', 'شرح النظام', 'كيف استخدم النظام', 'تعليمات النظام', 'دليل', 'help', 'guide'];
        foreach ($generalHelpKeywords as $ghk) {
            $ghkNorm = SmartBotService::normalizeText($ghk);
            if ($normalized === $ghkNorm || str_starts_with($normalized, $ghkNorm)) {
                return self::handleGeneralHelpOverview($user);
            }
        }

        $bestMatch = null;
        $highestScore = 0;

        foreach ($guides as $guide) {
            $score = 0;

            // 1. مطابقة الكلمات المفتاحية المخصصة (سواء كعبارة كاملة أو بتطابق الكلمات المكونة)
            foreach ($guide['keywords'] as $kw) {
                $kwNorm = SmartBotService::normalizeText($kw);
                if (str_contains($normalized, $kwNorm) || str_contains($expanded, $kwNorm)) {
                    $score += 35;
                    continue;
                }

                $kwTokens = preg_split('/\s+/u', $kwNorm);
                $matchedTokens = 0;
                foreach ($kwTokens as $kt) {
                    $ktNoAl = preg_replace('/^ال/u', '', $kt);
                    if (mb_strlen($ktNoAl) >= 3) {
                        if (str_contains($normalized, $kt) || str_contains($expanded, $kt) ||
                            str_contains($normalized, $ktNoAl) || str_contains($expanded, $ktNoAl)) {
                            $matchedTokens++;
                        }
                    }
                }
                if ($matchedTokens > 0 && $matchedTokens === count($kwTokens)) {
                    $score += 35;
                }
            }

            // 2. مطابقة العنوان
            $titleNorm = SmartBotService::normalizeText($guide['title']);
            $titleTokens = preg_split('/\s+/u', $titleNorm);
            foreach ($titleTokens as $t) {
                if (mb_strlen($t) >= 4 && (str_contains($normalized, $t) || str_contains($expanded, $t))) {
                    $score += 15;
                }
            }

            if ($score > $highestScore) {
                $highestScore = $score;
                $bestMatch = $guide;
            }
        }

        if ($bestMatch && $highestScore >= 25) {
            // التحقق من الصلاحيات: هل يحق للسائل الاطلاع على هذا الدليل؟
            if (self::canUserAccessGuide($bestMatch, $user)) {
                return self::formatGuideForBot($bestMatch, $user);
            } else {
                return self::handleRestrictedGuideResponse($bestMatch, $user);
            }
        }

        return null;
    }

