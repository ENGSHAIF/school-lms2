    /**
     * تحويل مقال الدليل إلى رسالة شات منسقة للمساعد الذكي مع الروابط والتنبيهات
     */
    public static function formatGuideForBot(array $guide, ?User $user = null): array
    {
        $reply = "📖 **دليل النظام: {$guide['title']}**\n\n";
        
        // التحقق من إمكانية فتح الشاشة
        $canOpenScreen = false;
        if ($user) {
            if ($user->isAdmin() || $user->isSupervisor() || $user->isTeacher() || $user->isAccountant() || ($user->permissionGroup && $user->permissionGroup->isAdminGroup())) {
                $canOpenScreen = true;
            } elseif ($user->isStudent() && str_contains($guide['route'], 'student')) {
                $canOpenScreen = true;
            } elseif ($user->isParent() && str_contains($guide['route'], 'parent')) {
                $canOpenScreen = true;
            }
        }

        if ($canOpenScreen) {
            $reply .= "📌 **الشاشة المسؤولة:** [{$guide['screen']}]({$guide['route']})\n";
        } else {
            $reply .= "📌 **الشاشة المسؤولة:** `{$guide['screen']}` *(تتطلب صلاحيات دخول)*\n";
        }

        $reply .= "💡 {$guide['summary']}\n\n";
        $reply .= "📋 **الخطوات العملية:**\n";

        foreach ($guide['steps'] as $index => $step) {
            $reply .= " " . ($index + 1) . ". {$step}\n";
        }

        if (!empty($guide['tip'])) {
            $reply .= "\n💡 **تلميح مهم:** {$guide['tip']}\n";
        }

        if ($canOpenScreen) {
            $reply .= "\n👉 يمكنك التوجه للشاشة مباشرة عبر الرابط أعلاه لتطبيق الخطوات!";
        } else {
            $reply .= "\n🔒 *تنبيه:* لا يمكن فتح الشاشة إلا إذا كان حسابك يملك الصلاحيات المحددة لها.";
        }

        return [
            'reply' => $reply,
            'matched_intent' => 'system_guide_' . $guide['id'],
            'suggestions' => [
                "📖 فتح مركز المساعدة الكامل",
                "كيف أصنع كويز أو اختبار؟",
                "كيف أضيف دورة أو مستوى؟",
                "كيف أقيم الطلاب وأرصد الحضور؟",
            ],
        ];
    }
